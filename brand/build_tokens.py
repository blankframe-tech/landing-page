#!/usr/bin/env python3
"""Build the BlankFrame design tokens from brand/tokens.json.

Writes tokens.css (CSS custom properties), tailwind.css (Tailwind v4 @theme),
blankframe_tokens.dart (Flutter constants + ThemeData) and the token tables in
brand/index.html. Every run also checks that each text pair passes WCAG AA and
that the home page's :root palette still matches the tokens.

    python3 brand/build_tokens.py           # regenerate
    python3 brand/build_tokens.py --check   # fail if anything is stale
"""
import html
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
T = json.loads((HERE / "tokens.json").read_text())
HEAD = "GENERATED by brand/build_tokens.py from brand/tokens.json. Edit that, then rerun."
THEMES = ("light", "dark")
# (text, background) pairs that must reach 4.5:1 in both themes
AA_PAIRS = [("ink", "bg"), ("ink", "card"), ("muted", "bg"), ("muted", "card"),
            ("accent-text", "bg"), ("accent-text", "card"), ("on-accent", "accent-text")]
# home page :root variable -> token value; the site has no build step, so it keeps its own copy
SITE_VARS = {f"--{k}": T["color"][k]["light"] for k in
             ("bg", "card", "ink", "ink-soft", "muted", "faint", "line", "accent")}
SITE_VARS |= {"--radius-lg": f"{T['radius']['lg']}px", "--radius-md": f"{T['radius']['md']}px",
              "--max-w": f"{T['layout']['max-w']}px"}


def contrast(a, b):
    def lum(hex_):
        c = [int(hex_[i:i + 2], 16) / 255 for i in (1, 3, 5)]
        c = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
        return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
    hi, lo = sorted((lum(a), lum(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def font_stack(names):
    return ", ".join(n if n in ("serif", "sans-serif", "-apple-system") else f'"{n}"' for n in names)


def camel(key):
    head, *rest = key.split("-")
    return head + "".join(p.title() for p in rest)


def ease_css():
    return "cubic-bezier({}, {}, {}, {})".format(*T["motion"]["ease"])


def build_css():
    def colors(theme, indent):
        return "\n".join(f"{indent}--bf-{k}: {v[theme]};" for k, v in T["color"].items())
    m = T["motion"]
    static = [*(f"  --bf-font-{k}: {font_stack(v)};" for k, v in T["font"].items()),
              *(f"  --bf-radius-{k}: {v}px;" for k, v in T["radius"].items()),
              *(f"  --bf-space-{k}: {v}px;" for k, v in T["space"].items()),
              f"  --bf-max-w: {T['layout']['max-w']}px;",
              f"  --bf-ease: {ease_css()};",
              *(f"  --bf-dur-{k}: {m[k]}ms;" for k in ("fast", "base", "slow")),
              *(f"  --bf-shadow-{k}: {v};" for k, v in T["shadow"].items())]
    return f"""/* {HEAD} */
:root {{
  color-scheme: light;
{colors("light", "  ")}
{chr(10).join(static)}
}}
@media (prefers-color-scheme: dark) {{
  :root:not([data-theme="light"]) {{
    color-scheme: dark;
{colors("dark", "    ")}
  }}
}}
:root[data-theme="dark"] {{
  color-scheme: dark;
{colors("dark", "  ")}
}}
@media (prefers-reduced-motion: reduce) {{
  :root {{ --bf-dur-fast: 0ms; --bf-dur-base: 0ms; --bf-dur-slow: 0ms; }}
}}
"""


def build_tailwind():
    lines = [*(f"  --color-bf-{k}: var(--bf-{k});" for k in T["color"]),
             *(f"  --font-bf-{k}: var(--bf-font-{k});" for k in T["font"]),
             *(f"  --radius-bf-{k}: var(--bf-radius-{k});" for k in T["radius"]),
             *(f"  --shadow-bf-{k}: var(--bf-shadow-{k});" for k in T["shadow"]),
             "  --ease-bf: var(--bf-ease);"]
    return f"""/* {HEAD}
   Tailwind v4: @import "tokens.css" before this file. Gives bg-bf-bg, text-bf-ink,
   border-bf-line, rounded-bf-md, font-bf-display, shadow-bf-card, ease-bf.
   Spacing is Tailwind's own 4px scale, which matches --bf-space-*. */
@theme inline {{
{chr(10).join(lines)}
}}
"""


def build_dart():
    def argb(hex_):
        return f"Color(0xFF{hex_[1:].upper()})"
    names = [camel(k) for k in T["color"]]
    fields = "\n".join(f"  final Color {n};" for n in names)
    ctor = ", ".join(f"required this.{n}" for n in names)

    def inst(theme):
        return "\n".join(f"    {camel(k)}: {argb(v[theme])}," for k, v in T["color"].items())
    fonts = "\n".join(f"  static const {k} = '{v[0]}';" for k, v in T["font"].items())
    radius = "\n".join(f"  static const double {k} = {v};" for k, v in T["radius"].items())
    space = "\n".join(f"  static const double s{k} = {v};" for k, v in T["space"].items())
    m = T["motion"]
    return f"""// {HEAD}
// Copy into a Flutter app (e.g. lib/core/theme/) and use bfTheme() or the constants.
// Fonts are family names only: bundle them in pubspec.yaml or load them with google_fonts.
import 'package:flutter/material.dart';

class BfColors {{
  const BfColors._({{{ctor}}});

{fields}

  static const light = BfColors._(
{inst("light")}
  );

  static const dark = BfColors._(
{inst("dark")}
  );

  static BfColors of(Brightness brightness) =>
      brightness == Brightness.dark ? dark : light;
}}

abstract final class BfFont {{
{fonts}
}}

abstract final class BfRadius {{
{radius}
}}

abstract final class BfSpace {{
{space}
}}

abstract final class BfMotion {{
  static const ease = Cubic({", ".join(str(x) for x in m["ease"])});
  static const fast = Duration(milliseconds: {m["fast"]});
  static const base = Duration(milliseconds: {m["base"]});
  static const slow = Duration(milliseconds: {m["slow"]});
}}

const double bfMaxWidth = {T["layout"]["max-w"]};

/// The BlankFrame family theme. Pass [accent] to keep a product's own brand colour;
/// it must reach 4.5:1 against [BfColors.onAccent].
ThemeData bfTheme(Brightness brightness, {{Color? accent}}) {{
  final c = BfColors.of(brightness);
  final primary = accent ?? c.accentText;
  final scheme = ColorScheme.fromSeed(seedColor: primary, brightness: brightness)
      .copyWith(
    primary: primary,
    onPrimary: c.onAccent,
    surface: c.card,
    onSurface: c.ink,
    onSurfaceVariant: c.muted,
    outline: c.line,
    outlineVariant: c.line,
  );
  final base = ThemeData(
    useMaterial3: true,
    brightness: brightness,
    colorScheme: scheme,
    scaffoldBackgroundColor: c.bg,
    fontFamily: BfFont.body,
    dividerTheme: DividerThemeData(color: c.line, thickness: 1),
    cardTheme: CardThemeData(
      color: c.card,
      elevation: 0,
      margin: EdgeInsets.zero,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(BfRadius.md),
        side: BorderSide(color: c.line),
      ),
    ),
    filledButtonTheme: FilledButtonThemeData(
      style: FilledButton.styleFrom(
        shape: const StadiumBorder(),
        padding: const EdgeInsets.symmetric(
            horizontal: BfSpace.s6, vertical: BfSpace.s3),
      ),
    ),
    outlinedButtonTheme: OutlinedButtonThemeData(
      style: OutlinedButton.styleFrom(
        shape: const StadiumBorder(),
        foregroundColor: c.ink,
        side: BorderSide(color: c.line),
      ),
    ),
    inputDecorationTheme: InputDecorationTheme(
      filled: true,
      fillColor: c.card,
      hintStyle: TextStyle(color: c.faint),
      border: OutlineInputBorder(
        borderRadius: BorderRadius.circular(BfRadius.sm),
        borderSide: BorderSide(color: c.line),
      ),
      enabledBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(BfRadius.sm),
        borderSide: BorderSide(color: c.line),
      ),
    ),
  );
  TextStyle? display(TextStyle? s) => s?.copyWith(
      fontFamily: BfFont.display, fontWeight: FontWeight.w700, letterSpacing: -0.5);
  final t = base.textTheme;
  return base.copyWith(
    textTheme: t.copyWith(
      displayLarge: display(t.displayLarge),
      displayMedium: display(t.displayMedium),
      displaySmall: display(t.displaySmall),
      headlineLarge: display(t.headlineLarge),
      headlineMedium: display(t.headlineMedium),
      headlineSmall: display(t.headlineSmall),
    ),
  );
}}
"""


def build_tables():
    e = html.escape
    rows = []
    for k, v in T["color"].items():
        sw = "".join(f'<span class="sw" style="background:{v[t]}" title="{t} {v[t]}"></span>' for t in THEMES)
        rows.append(f'<tr><td class="sws">{sw}</td><td><code>--bf-{k}</code></td>'
                    f'<td><code>{v["light"]}</code></td><td><code>{v["dark"]}</code></td><td>{e(v["use"])}</td></tr>')
    pairs = []
    for fg, bg in AA_PAIRS:
        cells = "".join(
            f'<td><span class="pair" style="color:{T["color"][fg][t]};background:{T["color"][bg][t]}">Aa</span> '
            f'{contrast(T["color"][fg][t], T["color"][bg][t]):.1f}:1</td>' for t in THEMES)
        pairs.append(f"<tr><td><code>{fg}</code> on <code>{bg}</code></td>{cells}</tr>")
    m = T["motion"]
    scales = [*(f'<tr><td><code>--bf-radius-{k}</code></td><td>{v}px</td>'
                f'<td><span class="rad" style="border-radius:{min(v, 28)}px"></span></td></tr>'
                for k, v in T["radius"].items()),
              *(f'<tr><td><code>--bf-space-{k}</code></td><td>{v}px</td>'
                f'<td><span class="bar" style="width:{v}px"></span></td></tr>' for k, v in T["space"].items()),
              f'<tr><td><code>--bf-max-w</code></td><td>{T["layout"]["max-w"]}px</td><td>Page content width</td></tr>',
              f'<tr><td><code>--bf-ease</code></td><td colspan="2"><code>{ease_css()}</code></td></tr>',
              *(f'<tr><td><code>--bf-dur-{k}</code></td><td>{m[k]}ms</td><td>0ms under reduced motion</td></tr>'
                for k in ("fast", "base", "slow"))]
    return f"""<!-- tokens:start ({HEAD}) -->
<h3>Colour</h3>
<div class="scroll"><table>
<thead><tr><th>Light / dark</th><th>Token</th><th>Light</th><th>Dark</th><th>Use</th></tr></thead>
<tbody>
{chr(10).join(rows)}
</tbody></table></div>
<h3>Text contrast</h3>
<p class="note">Every pair below passes WCAG AA (4.5:1); the build fails if one drops under it.</p>
<div class="scroll"><table>
<thead><tr><th>Pair</th><th>Light</th><th>Dark</th></tr></thead>
<tbody>
{chr(10).join(pairs)}
</tbody></table></div>
<h3>Radius, spacing, motion</h3>
<div class="scroll"><table>
<thead><tr><th>Token</th><th>Value</th><th>Preview</th></tr></thead>
<tbody>
{chr(10).join(scales)}
</tbody></table></div>
<!-- tokens:end -->"""


def problems():
    out = []
    for fg, bg in AA_PAIRS:
        for t in THEMES:
            r = contrast(T["color"][fg][t], T["color"][bg][t])
            if r < 4.5:
                out.append(f"{t}: {fg} on {bg} is {r:.2f}:1, under WCAG AA 4.5:1")
    site = (HERE.parent / "index.html").read_text()
    root = re.search(r":root\s*\{(.*?)\}", site, re.S).group(1)
    have = dict(re.findall(r"(--[\w-]+)\s*:\s*([^;]+);", root))
    for var, want in SITE_VARS.items():
        if have.get(var, "").strip().upper() != want.upper():
            out.append(f"index.html {var} is {have.get(var)!r}, tokens say {want}")
    return out


def main():
    check = "--check" in sys.argv
    page = HERE / "index.html"
    page_text = page.read_text()
    marker = re.compile(r"<!-- tokens:start.*?<!-- tokens:end -->", re.S)
    assert marker.search(page_text), "brand/index.html lost its tokens:start/end markers"
    outputs = {
        HERE / "tokens.css": build_css(),
        HERE / "tailwind.css": build_tailwind(),
        HERE / "blankframe_tokens.dart": build_dart(),
        page: marker.sub(lambda _: build_tables(), page_text),
    }
    errs = problems()
    for path, text in outputs.items():
        if not path.exists() or path.read_text() != text:
            if check:
                errs.append(f"{path.name} is stale: run python3 brand/build_tokens.py")
            else:
                path.write_text(text)
                print(f"wrote {path.relative_to(HERE.parent)}")
    for e in errs:
        print(f"FAIL {e}", file=sys.stderr)
    sys.exit(1 if errs else 0)


if __name__ == "__main__":
    main()
